#!/usr/bin/env python3
"""
ESPKV7 firmware signing tool (ECDSA P-256 + SHA-256).

  python tools/ota_tool.py genkey                 one time: create key pair + src/ota_pubkey.h
  python tools/ota_tool.py sign  firmware.bin     create firmware.espkv7 (image + 64-byte signature)
  python tools/ota_tool.py verify firmware.espkv7 check a signed file against the private key's public half

The PRIVATE key (tools/keys/ota_private.pem) must never be committed or shared.
Back it up somewhere safe: without it you cannot sign future updates.
Requires:  pip install cryptography
"""
import argparse, hashlib, pathlib, sys
from cryptography.hazmat.primitives import hashes, serialization
from cryptography.hazmat.primitives.asymmetric import ec
from cryptography.hazmat.primitives.asymmetric.utils import decode_dss_signature, encode_dss_signature
from cryptography.exceptions import InvalidSignature

ROOT = pathlib.Path(__file__).resolve().parent.parent
KEY_DIR = ROOT / "tools" / "keys"
PRIV = KEY_DIR / "ota_private.pem"
PUBHDR = ROOT / "src" / "ota_pubkey.h"
SIG_LEN = 64


def load_private():
    if not PRIV.exists():
        sys.exit(f"No private key at {PRIV}. Run 'genkey' first.")
    return serialization.load_pem_private_key(PRIV.read_bytes(), password=None)


def pub_bytes(pub):
    return pub.public_bytes(serialization.Encoding.X962, serialization.PublicFormat.UncompressedPoint)


def cmd_genkey(_):
    if PRIV.exists():
        sys.exit(f"Refusing to overwrite existing key {PRIV}")
    KEY_DIR.mkdir(parents=True, exist_ok=True)
    key = ec.generate_private_key(ec.SECP256R1())
    PRIV.write_bytes(key.private_bytes(
        serialization.Encoding.PEM,
        serialization.PrivateFormat.PKCS8,
        serialization.NoEncryption()))
    try:
        PRIV.chmod(0o600)
    except OSError:
        pass
    raw = pub_bytes(key.public_key())
    body = ",\n    ".join(", ".join(f"0x{b:02x}" for b in raw[i:i + 13]) for i in range(0, len(raw), 13))
    PUBHDR.write_text(
        "#pragma once\n#include <stdint.h>\n"
        "// Generated by tools/ota_tool.py genkey. PUBLIC key only (safe to commit).\n"
        "// ECDSA P-256, uncompressed point.\n"
        f"static const uint8_t OTA_PUBKEY[65] = {{\n    {body}\n}};\n")
    print(f"Private key : {PRIV}   (KEEP SECRET, back it up, never commit)")
    print(f"Public key  : {PUBHDR}  (rebuild and flash the firmware once over USB)")


def cmd_sign(a):
    key = load_private()
    src = pathlib.Path(a.firmware)
    image = src.read_bytes()
    if image[:1] != b"\xe9":
        sys.exit("This does not look like an ESP32 firmware image (first byte should be 0xE9).")
    der = key.sign(image, ec.ECDSA(hashes.SHA256()))
    r, s = decode_dss_signature(der)
    sig = r.to_bytes(32, "big") + s.to_bytes(32, "big")
    out = pathlib.Path(a.output) if a.output else src.with_suffix(".espkv7")
    out.write_bytes(image + sig)
    print(f"Signed: {out}  ({len(image)} byte image + {SIG_LEN} byte signature)")
    print(f"SHA-256 of image: {hashlib.sha256(image).hexdigest()}")


def cmd_verify(a):
    key = load_private()
    data = pathlib.Path(a.file).read_bytes()
    if len(data) <= SIG_LEN:
        sys.exit("File too small")
    image, sig = data[:-SIG_LEN], data[-SIG_LEN:]
    der = encode_dss_signature(int.from_bytes(sig[:32], "big"), int.from_bytes(sig[32:], "big"))
    try:
        key.public_key().verify(der, image, ec.ECDSA(hashes.SHA256()))
    except InvalidSignature:
        sys.exit("INVALID signature")
    print("Signature OK")


p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
sub = p.add_subparsers(dest="cmd", required=True)
sub.add_parser("genkey").set_defaults(fn=cmd_genkey)
s1 = sub.add_parser("sign"); s1.add_argument("firmware"); s1.add_argument("-o", "--output"); s1.set_defaults(fn=cmd_sign)
s2 = sub.add_parser("verify"); s2.add_argument("file"); s2.set_defaults(fn=cmd_verify)
args = p.parse_args()
args.fn(args)
