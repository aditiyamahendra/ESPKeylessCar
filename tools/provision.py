#!/usr/bin/env python3
"""
Factory provisioning: gives each unit its own Wi-Fi password and serial number.

  python tools/provision.py                 generate, build and flash one unit
  python tools/provision.py --port /dev/ttyACM0
  python tools/provision.py --dry-run       only generate and print (no build/flash)

It writes src/secrets.h (git-ignored), builds and uploads with PlatformIO, then
appends serial + password to tools/provisioning_log.csv (git-ignored) and prints
the text for the label and quick start card. KEEP THE LOG PRIVATE AND BACKED UP:
it is the only record of each unit's password.
"""
import argparse, csv, datetime, pathlib, secrets, subprocess, sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
SECRETS = ROOT / "src" / "secrets.h"
LOG = ROOT / "tools" / "provisioning_log.csv"
ALPHABET = "ABCDEFGHJKLMNPQRSTUVWXYZabcdefghijkmnpqrstuvwxyz23456789"  # no 0 O 1 l I
PW_LEN = 14
PREFIX = "ESPKV7"


def next_serial():
    n = 0
    if LOG.exists():
        with LOG.open(newline="") as f:
            for row in csv.DictReader(f):
                try:
                    n = max(n, int(row["serial"].split("-")[-1]))
                except (KeyError, ValueError):
                    pass
    return f"{PREFIX}-{n + 1:05d}"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--port")
    ap.add_argument("--dry-run", action="store_true")
    a = ap.parse_args()

    serial = next_serial()
    password = "".join(secrets.choice(ALPHABET) for _ in range(PW_LEN))

    SECRETS.write_text(
        "#pragma once\n"
        "// Generated by tools/provision.py for ONE unit. Git-ignored. Do not commit.\n"
        f'#define AP_PASSWORD "{password}"\n'
        f'#define UNIT_SERIAL "{serial}"\n')

    if not a.dry_run:
        cmd = ["pio", "run", "-t", "upload"]
        if a.port:
            cmd += ["--upload-port", a.port]
        if subprocess.run(cmd, cwd=ROOT).returncode != 0:
            sys.exit("Build or upload FAILED. Nothing was logged for this serial.")

    new = not LOG.exists()
    with LOG.open("a", newline="") as f:
        w = csv.writer(f)
        if new:
            w.writerow(["serial", "wifi_password", "date"])
        w.writerow([serial, password, datetime.datetime.now().isoformat(timespec="seconds")])

    print("\n=== LABEL / QUICK START CARD ===")
    print(f"Serial   : {serial}")
    print("Wi-Fi    : ESPKV7-Keyless")
    print(f"Password : {password}")


main()
